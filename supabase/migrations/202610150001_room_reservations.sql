alter table public.properties add column if not exists latitude double precision;
alter table public.properties add column if not exists longitude double precision;

create table if not exists public.room_reservations (
  id bigint generated by default as identity primary key,
  room_id bigint not null references public.rooms(id) on delete cascade,
  tenant_name text not null,
  phone text not null,
  amount_paid numeric(12, 2) not null check (amount_paid > 0),
  move_in_date date not null,
  status text not null default 'ACTIVE' check (status in ('ACTIVE', 'CONVERTED', 'CANCELLED')),
  created_at timestamptz not null default now()
);

create unique index if not exists room_reservations_one_active_per_room
  on public.room_reservations(room_id) where status = 'ACTIVE';

alter table public.room_reservations enable row level security;

drop policy if exists "Property owners manage room reservations"
  on public.room_reservations;

create policy "Property owners manage room reservations"
  on public.room_reservations for all
  using (exists (
    select 1 from public.rooms r
    join public.properties p on p.id = r.property_id
    where r.id = room_reservations.room_id and p.user_id = auth.uid()
  ))
  with check (exists (
    select 1 from public.rooms r
    join public.properties p on p.id = r.property_id
    where r.id = room_reservations.room_id and p.user_id = auth.uid()
  ));

grant select, insert, update, delete on public.room_reservations to authenticated;
grant usage, select on sequence public.room_reservations_id_seq to authenticated;

create or replace function public.reserve_room(
  p_room_id bigint,
  p_tenant_name text,
  p_phone text,
  p_amount_paid numeric,
  p_move_in_date date
) returns void
language plpgsql
security invoker
set search_path = public
as $$
begin
  update public.rooms set status = 'BOOKED'
  where id = p_room_id and status = 'AVAILABLE';
  if not found then
    raise exception 'Phòng không còn trống để nhận cọc';
  end if;

  insert into public.room_reservations(room_id, tenant_name, phone, amount_paid, move_in_date)
  values (p_room_id, p_tenant_name, p_phone, p_amount_paid, p_move_in_date);
end;
$$;
grant execute on function public.reserve_room(bigint, text, text, numeric, date) to authenticated;

create or replace function public.finish_room_checkout(
  p_room_id bigint,
  p_contract_id bigint,
  p_checkout_date date
) returns void
language plpgsql
security invoker
set search_path = public
as $$
begin
  update public.contracts set status = 'TERMINATED', end_date = p_checkout_date
  where id = p_contract_id and room_id = p_room_id and status = 'ACTIVE';
  if not found then
    raise exception 'Không tìm thấy hợp đồng đang hiệu lực cho phòng này';
  end if;

  update public.rooms set status = 'AVAILABLE' where id = p_room_id;
  if not found then
    raise exception 'Không cập nhật được trạng thái phòng';
  end if;
end;
$$;
grant execute on function public.finish_room_checkout(bigint, bigint, date) to authenticated;
